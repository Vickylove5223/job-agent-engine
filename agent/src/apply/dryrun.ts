// Dry-run CLI for the applier. Fills a real application form in a hosted Browserbase browser with
// a fake candidate, screenshots it, and NEVER clicks the final submit.
//
//   npx tsx --env-file=.env src/apply/dryrun.ts <job-url> [--fill-all]
//
// --fill-all  answer every unknown question with confidence 0.9 (first option / "N/A") so the
//             whole form gets exercised; without it unknown required questions → waiting_input.
// LinkedIn / Indeed URLs need BROWSERBASE_CONTEXT_ID (a context with a saved login, see connect.ts).
import { writeFile } from "node:fs/promises";
import { tmpdir } from "node:os";
import { join } from "node:path";
import type { Job, JobSource, Profile } from "@shared/types";
import type { ApplyInput, FieldAnswer, FieldQuestion } from "../contracts";
import { textToPdf } from "./common";
import { applyTo, methodFromUrl } from "./index";

const REQUIRED_ENV = ["BROWSERBASE_API_KEY", "BROWSERBASE_PROJECT_ID", "MODEL_API_KEY"] as const;

async function main() {
  const args = process.argv.slice(2);
  const url = args.find((a) => /^https?:\/\//i.test(a));
  const fillAll = args.includes("--fill-all");

  const missing = REQUIRED_ENV.filter((k) => !process.env[k]);
  if (missing.length) {
    console.log(
      [
        "Applier dry run needs a hosted browser (Browserbase) and a model key for Stagehand.",
        `Missing in agent/.env: ${missing.join(", ")}`,
        "",
        "  BROWSERBASE_API_KEY     https://www.browserbase.com → Settings → API keys",
        "  BROWSERBASE_PROJECT_ID  same page (Project ID)",
        "  MODEL_API_KEY           e.g. a Google AI Studio key (STAGEHAND_MODEL defaults to google/gemini-2.5-flash)",
        "  BROWSERBASE_CONTEXT_ID  optional — only for LinkedIn / Indeed (a context with a saved login)",
        "",
        "Then run: npx tsx --env-file=.env src/apply/dryrun.ts <job-url> [--fill-all]",
      ].join("\n"),
    );
    process.exit(0);
  }
  if (!url) {
    console.log("Usage: npx tsx --env-file=.env src/apply/dryrun.ts <job-url> [--fill-all]");
    process.exit(0);
  }

  const resumePath = join(tmpdir(), "test-candidate-resume.pdf");
  await writeFile(
    resumePath,
    textToPdf(
      [
        "Test Candidate",
        "test@example.com | +1 415 555 0100 | San Francisco, CA",
        "",
        "EXPERIENCE",
        "Software Engineer, Example Corp (2021 - present)",
        "- Built TypeScript services and React front ends.",
        "",
        "EDUCATION",
        "B.Sc. Computer Science, Example University (2017 - 2021)",
      ].join("\n"),
    ),
  );

  const method = methodFromUrl(url);
  const source: JobSource =
    method === "linkedin_easy" ? "linkedin" : method === "indeed" ? "indeed" : method === "external" ? "adzuna" /* any non-ATS source */ : method;
  const now = new Date().toISOString();
  const job: Job & { id: string } = {
    id: "dryrun",
    source,
    externalId: "dryrun",
    url,
    applyUrl: url,
    applyMethod: method,
    title: "Software Engineer",
    company: "Example Co",
    location: "Remote",
    remote: true,
    description: "Dry-run job",
    foundAt: now,
    status: "ready",
    attempts: 0,
    updatedAt: now,
  };
  const profile: Profile = {
    fullName: "Test Candidate",
    email: "test@example.com",
    phone: "+14155550100",
    location: "San Francisco, CA",
    country: "US",
    links: { linkedin: "https://www.linkedin.com/in/test-candidate", github: "https://github.com/test-candidate" },
    standardAnswers: {},
  };

  const input: ApplyInput = {
    job,
    profile,
    facts: [],
    resumePdfPath: resumePath,
    coverLetter: { text: "Dear hiring team,\n\nThis is a dry-run cover letter generated by the job agent test harness.\n\nBest regards,\nTest Candidate" },
    contextId: process.env.BROWSERBASE_CONTEXT_ID || undefined,
    dryRun: true,
    answer: async (f) => {
      const a = dryRunAnswer(f, fillAll);
      console.log(`  ? ${f.required ? "*" : " "} [${f.type}] ${f.label}${f.options ? ` {${f.options.slice(0, 6).join(" | ")}${f.options.length > 6 ? " …" : ""}}` : ""} → "${a.answer}" (${a.confidence})`);
      return a;
    },
  };

  console.log(`Dry run: ${url} (method ${method})`);
  const res = await applyTo(input);
  const shotPath = join(tmpdir(), `applier-dryrun-${Date.now()}.jpg`);
  if (res.screenshot) await writeFile(shotPath, res.screenshot);
  console.log(
    JSON.stringify(
      { ...res, screenshot: res.screenshot ? `${shotPath} (${Math.round(res.screenshot.byteLength / 1024)} KB)` : undefined },
      null,
      2,
    ),
  );
}

/** Deterministic, low-risk answers. Unknown → confidence 0.5 (or 0.9 with --fill-all). */
function dryRunAnswer(f: FieldQuestion, fillAll: boolean): FieldAnswer {
  const L = f.label.toLowerCase();
  const opts = f.options ?? [];
  const pick = (re: RegExp) => opts.find((o) => re.test(o));
  const ok = (answer: string, confidence = 0.95): FieldAnswer => ({ answer, confidence, basis: ["dryrun"] });

  if (/gender|race|ethnic|hispanic|veteran|disabilit|orientation|pronoun/.test(L)) {
    const d = pick(/decline|prefer not|don.?t wish|not to (say|disclose|answer)/i);
    if (d) return ok(d);
  }
  if (/authori[sz]ed|eligible to work|right to work|legally/.test(L)) return ok(pick(/^yes/i) ?? "Yes");
  if (/sponsor/.test(L)) return ok(pick(/^no/i) ?? "No");
  if (/years.*experience|experience.*years/.test(L)) return ok(opts.length ? (pick(/3|2-4|3-5/) ?? opts[0]!) : "3");
  if (/how did you hear|source|where did you (find|hear)/.test(L)) return ok(pick(/linkedin|job board|other|website/i) ?? (opts[0] ?? "Company website"));
  if (/privacy|consent|agree|acknowledge|terms/.test(L)) return ok(opts.length ? (pick(/agree|yes|accept|acknowledge/i) ?? opts[0]!) : "Yes");
  if (/relocat/.test(L)) return ok(pick(/^yes/i) ?? "Yes", 0.85);
  if (/salary|compensation|pay expectation/.test(L)) return ok("Open to discussion", 0.85);
  if (/notice period|start date|available to start/.test(L)) return ok("2 weeks", 0.85);
  if (fillAll) {
    if (opts.length) return ok(opts[0]!, 0.9);
    if (f.type === "number") return ok("1", 0.9);
    if (f.type === "checkbox") return ok("Yes", 0.9);
    return ok("N/A (dry run)", 0.9);
  }
  return { answer: opts[0] ?? "", confidence: 0.5, basis: ["dryrun: unknown"] };
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
